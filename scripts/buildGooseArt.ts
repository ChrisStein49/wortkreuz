// Turns the newsletter goose artwork (assets/geese/goose-yellow.svg, drawn in
// Inkscape) into a recolourable template: the yellow fills become the body
// colour (beak and feet can get their own), the purple line art the outline.
// Writes src/assets/gooseArt.ts for the app and mockups/goose-art.js for the
// static mockups.
//   npx tsx scripts/buildGooseArt.ts
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(import.meta.dirname, '..')
const svg = readFileSync(join(ROOT, 'assets', 'geese', 'goose-yellow.svg'), 'utf8')

function pathD(id: string): string {
  const m = svg.match(new RegExp(`<path[^>]*?\\sd="([^"]+)"[^>]*?id="${id}"`, 's'))
    ?? svg.match(new RegExp(`<path[^>]*?id="${id}"[^>]*?\\sd="([^"]+)"`, 's'))
  if (!m) throw new Error(`path ${id} not found`)
  return m[1].replace(/\s+/g, ' ').trim()
}

const art = {
  viewBox: svg.match(/viewBox="([^"]+)"/)![1],
  // line art, drawn first and shifted like in the source file
  outline: pathD('path6'),
  outlineShift: -2.4890211,
  eye: pathD('path5'),
  body: [pathD('path50'), pathD('path54'), pathD('path55')],
  beak: pathD('path51'),
  feet: [pathD('path52'), pathD('path53')],
}

// The six goose colours (variant C, chosen 2026-10-19): body colour, orange
// beak and feet, outline a darker shade of the body. The orange goose gets a
// darker beak so it doesn't vanish; the black goose a grey outline.
const BEAK = '#f2a900'
const darken = (hex: string, f: number) =>
  '#' + [1, 3, 5].map((i) => Math.round(parseInt(hex.slice(i, i + 2), 16) * f).toString(16).padStart(2, '0')).join('')
const palette = [
  { name: 'red', body: '#d62828' },
  { name: 'orange', body: '#f28c00', beak: '#a3520a' },
  { name: 'green', body: '#2e9e44' },
  { name: 'blue', body: '#1f5fd1' },
  { name: 'pink', body: '#e85aa8' },
  { name: 'black', body: '#222222', outline: '#5c5c5c' },
].map((g) => ({ name: g.name, body: g.body, beak: g.beak ?? BEAK, outline: g.outline ?? darken(g.body, 0.5) }))

const fn = `/** Goose colours in symbol order (symbol 0 = red, ...) */
export const GEESE = ${JSON.stringify(palette, null, 1)}

export interface GooseColors {
  body: string
  /** Beak and feet */
  beak: string
  outline: string
}

/** The newsletter goose as an SVG string in the given colours */
export function gooseSvg(c: GooseColors, attrs = ''): string {
  const fill = (d: string, color: string, width: number) =>
    \`<path d="\${d}" fill="\${color}" stroke="\${c.outline}" stroke-width="\${width}" stroke-linejoin="round" stroke-linecap="round" paint-order="stroke"/>\`
  return (
    \`<svg viewBox="\${ART.viewBox}" xmlns="http://www.w3.org/2000/svg" aria-hidden="true" \${attrs}>\` +
    \`<path d="\${ART.outline}" fill="\${c.outline}" transform="translate(\${ART.outlineShift})"/>\` +
    \`<path d="\${ART.eye}" fill="\${c.outline}"/>\` +
    ART.body.map((d) => fill(d, c.body, 2.31)).join('') +
    fill(ART.beak, c.beak, 2.83) +
    ART.feet.map((d) => fill(d, c.beak, 2.83)).join('') +
    '</svg>'
  )
}`

const header = '// Generated by scripts/buildGooseArt.ts from assets/geese/goose-yellow.svg – do not edit.\n'
mkdirSync(join(ROOT, 'src', 'assets'), { recursive: true })
writeFileSync(join(ROOT, 'src', 'assets', 'gooseArt.ts'), `${header}const ART = ${JSON.stringify(art, null, 1)}\n\n${fn}\n`)
writeFileSync(
  join(ROOT, 'mockups', 'goose-art.js'),
  `${header}const ART = ${JSON.stringify(art)}\n\n${fn.replace(/: GooseColors/g, '').replace(/export interface GooseColors \{[^}]*\}\n\n/s, '').replace(/\(d: string, color: string, width: number\)/, '(d, color, width)').replace(/\(c, attrs = ''\): string/, "(c, attrs = '')")}\n`,
)
console.log('wrote src/assets/gooseArt.ts and mockups/goose-art.js')
